def clean_hrefs(s, page):
    """Link to the address Google indexes. The host 308s /about.html to /about."""
    def fix(m):
        target, rest = m.group(1), m.group(2)
        if re.match(r'[a-z]+:', target):
            return m.group(0)
        path = posixpath.normpath(posixpath.join('/', posixpath.dirname(page), target))
        if path.endswith('/index'):
            path = path[:-5] or '/'
        return f'href="{path}{rest}"'
    return re.sub(r'href="([^"#?]+?)\.html((?:[?#][^"]*)?)"', fix, s)


