def div_end(s, start):
    depth = 0
    for m in re.compile(r'<(/?)div\b[^>]*>').finditer(s, start):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return m.end()
    raise ValueError('unbalanced div')


def main():
    index = open(f'{SITE}/index.html', encoding='utf-8').read()
    edge = re.search(r'<svg class="ribbon-edge".*?</svg>', index, re.S).group(0)
    edge = re.sub(r'\n\s*', '', edge)

    head = re.compile(r'(?:[ \t]*<!-- Generated by \.build/nav\.py.*?-->\n)?[ \t]*<header\b[^>]*\bdata-nav\b[^>]*>.*?</header>', re.S)
    bare = re.compile(r'<header class="(?:fixed top-0 left-0 right-0 z-50|site-nav)">.*?</header>', re.S)
    done = []
    for path in sorted(glob.glob(f'{SITE}/**/*.html', recursive=True)):
        page = os.path.relpath(path, SITE)
        if page.startswith('quote/') or page.startswith('.build/'):
            continue
        s = open(path, encoding='utf-8').read()
        root = '../' * page.count('/')
        if 'data-nav' in s:
            s, n = head.subn(lambda _: header(page, root), s, count=1)
            assert n == 1, page
            if '<div data-mobile-nav' in s:
                start = s.index('<div data-mobile-nav')
                s = s[:start] + sheet(page, root, edge) + s[div_end(s, start):]
            else:
                # privacy.html shipped with a menu button and no menu
                end = s.index('</header>') + len('</header>')
                s = s[:end] + '\n\n  ' + sheet(page, root, edge) + s[end:]
        else:
            # 404 and thank-you carry the logo only
            prefix = '/' if page == '404.html' else root
            bar = f'<header class="site-nav">\n    <div class="site-nav-bar">\n      {logo(prefix, "site-nav-logo")}\n    </div>\n  </header>'
            s, n = bare.subn(lambda _: bar, s, count=1)
            assert n == 1, page
        prefix = '/' if page == '404.html' else root
        s, n = re.subn(r'<footer\b.*?</footer>', lambda _: footer(prefix, edge), s, count=1, flags=re.S)
        assert n == 1, page
        s = clean_hrefs(s, page)
        open(path, 'w', encoding='utf-8').write(s)
        done.append(page)
    print('nav written to', len(done), 'pages')


if __name__ == '__main__':
    main()
